    fun translateTimeAgo(textual: String): String {
        if (textual.equals("just now", ignoreCase = true)) return t("just_now", "just now")
        val match = Regex("^(\\d+)\\s+(second|minute|hour|day|week|month|year)s?\\s+ago", RegexOption.IGNORE_CASE).find(textual)
        if (match != null) {
            val (numStr, unit) = match.destructured
            val num = numStr.toLongOrNull() ?: return textual
            return timeAgo(num, unit.lowercase())
        }
        return textual
    }

