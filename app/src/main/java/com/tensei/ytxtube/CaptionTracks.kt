package com.tensei.ytxtube

import android.util.Log
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.util.Locale
import java.util.concurrent.ConcurrentHashMap

/**
 * One side-loadable caption track, already normalised to WebVTT.
 *
 * NewPipe's YouTube extractor asks timedtext for TTML. Media3's TTML parser is strict and a
 * single malformed cue used to abort the whole playback, which is why the player reported
 * "captions unavailable" on videos that do have captions. Flow reads the InnerTube caption
 * tracklist and plays VTT, so we do the same here.
 */
data class CaptionTrack(
    val languageTag: String,
    val label: String,
    val url: String,
    val autoGenerated: Boolean,
)

object CaptionTracks {
    private const val TAG = "YTXTubeCaptions"
    private const val MAX_AGE_MS = 3 * 60 * 60 * 1000L

    private class Entry(val tracks: List<CaptionTrack>, val at: Long)
    private val cache = ConcurrentHashMap<String, Entry>()

    fun get(videoId: String): List<CaptionTrack>? =
        cache[videoId]?.takeIf { System.currentTimeMillis() - it.at < MAX_AGE_MS }?.tracks

    fun put(videoId: String, tracks: List<CaptionTrack>) {
        if (tracks.isNotEmpty()) cache[videoId] = Entry(tracks, System.currentTimeMillis())
    }

    fun invalidate(videoId: String) {
        cache.remove(videoId)
    }

    fun invalidateAll() = cache.clear()

    /** Caption tracks that came back with the same extraction used for the streams. */
    fun fromStreamInfo(info: StreamInfo): List<CaptionTrack> =
        info.subtitles
            .mapNotNull(::fromSubtitles)
            .distinctBy { it.languageTag to it.autoGenerated }

    private fun fromSubtitles(sub: SubtitlesStream): CaptionTrack? {
        if (!sub.isUrl || sub.content.isBlank()) return null
        val tag = sub.languageTag.trim().ifBlank { "und" }
        val url = vttUrl(sub.content) ?: return null
        return CaptionTrack(
            languageTag = tag,
            label = label(tag, sub.isAutoGenerated),
            url = url,
            autoGenerated = sub.isAutoGenerated,
        )
    }

    /**
     * Fallback for the rare extraction where NewPipe returns no subtitle list at all. This is
     * the exact source Flow uses: the InnerTube player response's captionTracks array.
     */
    fun load(videoId: String): List<CaptionTrack> {
        get(videoId)?.let { return it }
        val response = runCatching { PlayerFallback.playerResponse(videoId) }.getOrNull() ?: return emptyList()
        val tracks = response.optJSONObject("captions")
            ?.optJSONObject("playerCaptionsTracklistRenderer")
            ?.optJSONArray("captionTracks")
            ?: return emptyList()

        val parsed = buildList {
            for (i in 0 until tracks.length()) {
                val obj = tracks.optJSONObject(i) ?: continue
                val base = obj.optString("baseUrl").takeIf { it.isNotBlank() } ?: continue
                val tag = obj.optString("languageCode").takeIf { it.isNotBlank() } ?: continue
                val auto = obj.optString("kind") == "asr"
                val url = vttUrl(base) ?: continue
                add(CaptionTrack(tag, label(tag, auto), url, auto))
            }
        }.distinctBy { it.languageTag to it.autoGenerated }

        if (parsed.isNotEmpty()) {
            cache[videoId] = Entry(parsed, System.currentTimeMillis())
            Log.i(TAG, "InnerTube supplied ${parsed.size} caption tracks for $videoId")
        }
        return parsed
    }

    private fun vttUrl(raw: String): String? {
        val url = raw.toHttpUrlOrNull() ?: return null
        return url.newBuilder().setQueryParameter("fmt", "vtt").build().toString()
    }

    private fun label(tag: String, auto: Boolean): String {
        val language = runCatching {
            Locale.forLanguageTag(tag).getDisplayLanguage(Locale.getDefault())
        }.getOrNull()?.takeIf { it.isNotBlank() && !it.equals("und", true) } ?: tag
        return if (auto) "$language (auto)" else language
    }
}
